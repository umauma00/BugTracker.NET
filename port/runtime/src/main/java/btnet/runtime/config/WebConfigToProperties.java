package btnet.runtime.config;

import javax.xml.stream.XMLInputFactory;
import javax.xml.stream.XMLStreamConstants;
import javax.xml.stream.XMLStreamException;
import javax.xml.stream.XMLStreamReader;
import java.io.IOException;
import java.io.InputStream;
import java.io.Writer;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayDeque;
import java.util.Deque;
import java.util.LinkedHashMap;
import java.util.Map;

/**
 * One-time generator (RULEBOOK §2A "Settings"): reads the <b>uncommented</b>
 * {@code <add key value>} entries of {@code <configuration><appSettings>} in
 * {@code src/BugTracker.Web/Web.config} (honouring {@code <remove key>} and {@code <clear/>},
 * a repeated key keeps the last value, as .NET's {@code NameValueSectionHandler}) and writes
 * them, in file order, to {@code port/web/src/main/resources/btnet-settings.properties}
 * (UTF-8, {@link java.util.Properties} escaping), which {@link ConfigurationManager} loads.
 * <p>
 * Usage (from the repository root):
 * {@code java -cp … btnet.runtime.config.WebConfigToProperties [Web.config] [output.properties]}.
 */
public final class WebConfigToProperties {
    private WebConfigToProperties() {}

    public static final String DEFAULT_INPUT = "src/BugTracker.Web/Web.config";
    public static final String DEFAULT_OUTPUT = "port/web/src/main/resources/" + ConfigurationManager.RESOURCE;

    public static void main(String[] args) throws IOException, XMLStreamException {
        Path in = Path.of(args.length > 0 ? args[0] : DEFAULT_INPUT);
        Path out = Path.of(args.length > 1 ? args[1] : DEFAULT_OUTPUT);
        Map<String, String> settings;
        try (InputStream is = Files.newInputStream(in)) {
            settings = readAppSettings(is);
        }
        if (out.getParent() != null) {
            Files.createDirectories(out.getParent());
        }
        try (Writer w = Files.newBufferedWriter(out, StandardCharsets.UTF_8)) {
            w.write(render(settings, in.toString().replace('\\', '/')));
        }
        System.out.println("Wrote " + settings.size() + " appSettings entries to " + out);
    }

    /** The appSettings of a Web.config, in order (comments are skipped by the XML parser). */
    public static Map<String, String> readAppSettings(InputStream xml) throws XMLStreamException {
        XMLInputFactory f = XMLInputFactory.newFactory();
        f.setProperty(XMLInputFactory.SUPPORT_DTD, false);
        f.setProperty(XMLInputFactory.IS_SUPPORTING_EXTERNAL_ENTITIES, false);
        XMLStreamReader r = f.createXMLStreamReader(xml);
        Map<String, String> result = new LinkedHashMap<>();
        Deque<String> path = new ArrayDeque<>();
        try {
            while (r.hasNext()) {
                int ev = r.next();
                if (ev == XMLStreamConstants.START_ELEMENT) {
                    String name = r.getLocalName();
                    boolean inAppSettings = path.size() == 2 && "appSettings".equals(path.peekFirst())
                            && "configuration".equals(path.peekLast());
                    if (inAppSettings) {
                        String key = attr(r, "key");
                        if ("add".equals(name) && key != null) {
                            String existing = findKey(result, key);
                            if (existing != null) result.remove(existing);
                            String value = attr(r, "value");
                            result.put(key, value == null ? "" : value);
                        } else if ("remove".equals(name) && key != null) {
                            String existing = findKey(result, key);
                            if (existing != null) result.remove(existing);
                        } else if ("clear".equals(name)) {
                            result.clear();
                        }
                    }
                    path.push(name);
                } else if (ev == XMLStreamConstants.END_ELEMENT) {
                    path.pop();
                }
            }
        } finally {
            r.close();
        }
        return result;
    }

    private static String attr(XMLStreamReader r, String name) {
        for (int i = 0; i < r.getAttributeCount(); i++) {
            if (r.getAttributeLocalName(i).equals(name)) return r.getAttributeValue(i);
        }
        return null;
    }

    private static String findKey(Map<String, String> m, String key) {
        for (String k : m.keySet()) {
            if (k.equalsIgnoreCase(key)) return k;   // appSettings keys are case-insensitive
        }
        return null;
    }

    /** The properties text written by {@link #main}. */
    public static String render(Map<String, String> settings, String source) {
        StringBuilder sb = new StringBuilder();
        sb.append("# Generated by btnet.runtime.config.WebConfigToProperties from ").append(source)
                .append(" <appSettings> - do not hand-edit (RULEBOOK 2A Settings)\n");
        for (Map.Entry<String, String> e : settings.entrySet()) {
            sb.append(escape(e.getKey(), true)).append('=').append(escape(e.getValue(), false)).append('\n');
        }
        return sb.toString();
    }

    /** {@link java.util.Properties} escaping; non-ASCII stays UTF-8 (the file is read as UTF-8). */
    static String escape(String s, boolean isKey) {
        StringBuilder sb = new StringBuilder(s.length() + 8);
        for (int i = 0; i < s.length(); i++) {
            char c = s.charAt(i);
            switch (c) {
                case '\\' -> sb.append("\\\\");
                case '\n' -> sb.append("\\n");
                case '\r' -> sb.append("\\r");
                case '\t' -> sb.append("\\t");
                case '\f' -> sb.append("\\f");
                case ' ' -> sb.append(isKey || i == 0 ? "\\ " : " ");
                case '=', ':', '#', '!' -> sb.append(isKey || i == 0 ? "\\" + c : String.valueOf(c));
                default -> {
                    if (c < 0x20) {
                        sb.append(String.format("\\u%04x", (int) c));
                    } else {
                        sb.append(c);
                    }
                }
            }
        }
        return sb.toString();
    }
}
