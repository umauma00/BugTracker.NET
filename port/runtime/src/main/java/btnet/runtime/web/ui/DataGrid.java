package btnet.runtime.web.ui;

import btnet.runtime.EventArgs;

import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.Map;
import java.util.function.BiConsumer;

/**
 * {@code System.Web.UI.WebControls.DataGrid} (B5, [J-U1]). Built in the field initializer:
 * <pre>
 * public final DataGrid MyDataGrid = control(new DataGrid("MyDataGrid"))
 *         .BorderColor("black").CssClass("datat").CellPadding(3).AutoGenerateColumns(false)
 *         .HeaderStyle("datah").ItemStyle("datad")
 *         .Column(new BoundColumn("File", "file"))
 *         .Column(new HyperLinkColumn("Download", "Download", "url", "_blank"))
 *         .Column(new ButtonColumn("Delete", "Delete", "dlt"));
 * // constructor: MyDataGrid.OnItemCommand(this::my_button_click);
 * </pre>
 * {@code DataBind} creates the header item {@code ctl01} and one {@link DataGridItem} per row
 * ({@code ctl02}…), runs each column's cell initialization (TemplateColumn factories) and binding.
 * The item count is kept in view state; on postback the items, their cells and column controls are
 * recreated before their own state loads, so {@code Items()}, {@code FindControl} and
 * {@code Cells().get(i).Text()} work although the grid is bound only on GET. Rendered by
 * {@code bt:control} on {@code <table>}: {@code cellspacing="0" cellpadding rules="all" border="1"
 * style="border-color:…;border-collapse:collapse;"}, header row (class of {@code HeaderStyle}), item
 * rows (class of {@code ItemStyle}); an unbound grid renders nothing.
 */
public class DataGrid extends WebControl<DataGrid> {
    private final List<DataGridColumn<?>> columns = new ArrayList<>();
    private Object dataSource;
    private BiConsumer<Object, DataGridCommandEventArgs> itemCommand;
    private DataGridItem header;
    private final List<DataGridItem> items = new ArrayList<>();
    private final TableItemStyle headerStyle = new TableItemStyle();
    private final TableItemStyle itemStyle = new TableItemStyle();
    private final TableItemStyle alternatingItemStyle = new TableItemStyle();

    /** {@code TableItemStyle} of {@code <HeaderStyle>}/{@code <ItemStyle>}: only {@code CssClass} is used by the source. */
    public static final class TableItemStyle {
        private String cssClass = "";

        public String CssClass() { return cssClass; }

        public TableItemStyle CssClass(String v) { this.cssClass = v == null ? "" : v; return this; }
    }

    public DataGrid(String id) {
        super(id);
    }

    @Override
    public boolean IsNamingContainer() { return true; }

    // ---- configuration ----

    /** {@code Columns}. */
    public List<DataGridColumn<?>> Columns() { return columns; }

    /** Fluent {@code Columns.Add(c)}. */
    public DataGrid Column(DataGridColumn<?> c) { columns.add(c); return this; }

    public TableItemStyle HeaderStyle() { return headerStyle; }

    /** Fluent {@code <HeaderStyle CssClass="…">}. */
    public DataGrid HeaderStyle(String cssClass) { headerStyle.CssClass(cssClass); return this; }

    public TableItemStyle ItemStyle() { return itemStyle; }

    /** Fluent {@code <ItemStyle CssClass="…">}. */
    public DataGrid ItemStyle(String cssClass) { itemStyle.CssClass(cssClass); return this; }

    public TableItemStyle AlternatingItemStyle() { return alternatingItemStyle; }

    public DataGrid AlternatingItemStyle(String cssClass) { alternatingItemStyle.CssClass(cssClass); return this; }

    public boolean AutoGenerateColumns() { return vsBool("AutoGenerateColumns", true); }

    /** {@code AutoGenerateColumns}; every source grid sets {@code false}. TODO(port): automatic columns are not generated by the runtime. */
    public DataGrid AutoGenerateColumns(boolean v) { vsSet("AutoGenerateColumns", v); return this; }

    public int CellPadding() { return vsInt("CellPadding", -1); }

    public DataGrid CellPadding(int v) { vsSet("CellPadding", v); return this; }

    public int CellSpacing() { return vsInt("CellSpacing", 0); }

    public DataGrid CellSpacing(int v) { vsSet("CellSpacing", v); return this; }

    public boolean ShowHeader() { return vsBool("ShowHeader", true); }

    public DataGrid ShowHeader(boolean v) { vsSet("ShowHeader", v); return this; }

    public Object DataSource() { return dataSource; }

    public DataGrid DataSource(Object v) { this.dataSource = v; return this; }

    /** {@code OnItemCommand="X"} → {@code OnItemCommand(this::X)} (B2 step 6). */
    public DataGrid OnItemCommand(BiConsumer<Object, DataGridCommandEventArgs> handler) {
        this.itemCommand = handler;
        return this;
    }

    // ---- items ----

    /** {@code Items}: the data items (header excluded), in row order. */
    public List<DataGridItem> Items() { return Collections.unmodifiableList(items); }

    /** {@code DataBind}: rebuilds the items from {@code DataSource} and binds every cell. */
    @Override
    public void DataBind() {
        Iterable<?> data = DataBinder.resolve(dataSource);
        List<Object> rows = new ArrayList<>();
        if (data != null) for (Object o : data) rows.add(o);
        createHierarchy(rows.size(), rows);
        vsSet("_itemCount", rows.size());
    }

    private void createHierarchy(int count, List<Object> rows) {
        Controls().Clear();
        items.clear();
        header = createItem(-1, ListItemType.Header, 1);
        for (int i = 0; i < count; i++) {
            DataGridItem item = createItem(i, i % 2 == 1 ? ListItemType.AlternatingItem : ListItemType.Item, i + 2);
            items.add(item);
            if (rows != null) {
                Object row = rows.get(i);
                item.DataItem(row);
                List<TableCell> cells = item.Cells();
                for (int c = 0; c < columns.size(); c++) columns.get(c).BindCell(cells.get(c), item, row);
                item.DataBind();
                item.DataItem(null);
            }
        }
    }

    private DataGridItem createItem(int index, ListItemType type, int number) {
        DataGridItem item = new DataGridItem(index, index, type);
        item.ID(Html.ctl(number));
        Controls().Add(item);
        for (int c = 0; c < columns.size(); c++) {
            TableCell cell = new TableCell();
            item.Controls().Add(cell);
            columns.get(c).InitializeCell(cell, c, type, item);
        }
        return item;
    }

    @Override
    public Map<String, Object> SaveViewState() {
        return super.SaveViewState();
    }

    /** Restores the item count and recreates the items (unbound) so the tree loads their controls' state next. */
    @Override
    public void LoadViewState(Map<String, ?> saved) {
        super.LoadViewState(saved);
        int count = vsInt("_itemCount", -1);
        if (count >= 0) createHierarchy(count, null);
    }

    /** Bound (now or before the postback)? */
    public boolean IsBound() { return vsInt("_itemCount", -1) >= 0; }

    @Override
    public boolean IsRenderSuppressed() { return !IsBound(); }

    // ---- events ----

    @Override
    protected boolean OnBubbleEvent(Object source, EventArgs args) {
        if (args instanceof DataGridCommandEventArgs e) {
            if (itemCommand != null) itemCommand.accept(this, e);
            return true;
        }
        return false;
    }

    // ---- rendering ----

    @Override
    protected String TagName() { return "table"; }

    @Override
    protected void AddAttributesToRender(Map<String, String> a) {
        super.AddAttributesToRender(a);
        a.put("cellspacing", Integer.toString(CellSpacing()));
        if (CellPadding() >= 0) a.put("cellpadding", Integer.toString(CellPadding()));
        a.put("rules", "all");
        a.put("border", "1");
    }

    @Override
    protected String RenderStyle() {
        String s = super.RenderStyle();
        String collapse = CellSpacing() == 0 ? "border-collapse:collapse;" : "";
        String all = (s == null ? "" : s) + collapse;
        return all.isEmpty() ? null : all;
    }

    @Override
    protected String RenderInnerHtml(String templateTag) {
        StringBuilder sb = new StringBuilder();
        if (header != null && ShowHeader()) {
            sb.append("\r\n\t");
            header.render(sb, columns, headerStyle.CssClass());
        }
        for (DataGridItem item : items) {
            sb.append("\r\n\t");
            String css = item.ItemType() == ListItemType.AlternatingItem && !alternatingItemStyle.CssClass().isEmpty()
                    ? alternatingItemStyle.CssClass() : itemStyle.CssClass();
            item.render(sb, columns, css);
        }
        sb.append("\r\n");
        return sb.toString();
    }
}
